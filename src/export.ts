import type { AnalysisResult, ModelComparisonResult } from './types';

export function generateMarkdownReport(result: AnalysisResult): string {
  const { repo, issues, latencyMs, modelUsed } = result;

  let md = `# ClayPull Report\n\n`;

  if (modelUsed || latencyMs) {
    md += `*Generated by ClayPull using **${modelUsed || 'AI Model'}**${latencyMs ? ` in ${(latencyMs / 1000).toFixed(2)}s` : ''} on ${new Date().toLocaleDateString()}*\n\n`;
  }

  // Repo overview
  md += `## Repository Overview\n\n`;
  md += `**Purpose:** ${repo.purpose}\n\n`;
  md += `**Stack:** ${repo.stack.join(', ')}\n\n`;

  if (repo.setupSteps.length > 0) {
    md += `### Setup Steps\n`;
    repo.setupSteps.forEach((s, i) => { md += `${i + 1}. ${s}\n`; });
    md += `\n`;
  }

  if (repo.contributionRules.length > 0) {
    md += `### Contribution Rules\n`;
    repo.contributionRules.forEach((r) => { md += `- ${r}\n`; });
    md += `\n`;
  }

  // Issues
  md += `## Recommended Issues\n\n`;

  if (issues.length === 0) {
    md += `No suitable issues found for this repository.\n\n`;
    return md;
  }

  issues.forEach((issue, idx) => {
    md += `### ${idx + 1}. ${issue.title} (#${issue.number})\n\n`;
    md += `**Link:** ${issue.url}\n`;
    md += `**Fit Score:** ${Math.round(issue.fitScore * 100)}%\n`;
    md += `**Effort:** ${issue.effort}\n\n`;
    md += `**Why this issue:** ${issue.whyThisOne}\n\n`;
    md += `**Explanation:** ${issue.plainExplanation}\n\n`;

    if (issue.filesToTouch.length > 0) {
      md += `#### Files to Touch\n`;
      issue.filesToTouch.forEach((f) => {
        md += `- \`${f.path}\` ${f.verified ? '✅ (verified)' : '❓ (guess)'} — ${f.reason}\n`;
      });
      md += `\n`;
    }

    if (issue.plan.length > 0) {
      md += `#### Step-by-Step Plan\n`;
      issue.plan.forEach((step, i) => { md += `${i + 1}. ${step}\n`; });
      md += `\n`;
    }

    if (issue.risks.length > 0) {
      md += `#### Risks\n`;
      issue.risks.forEach((r) => { md += `- ⚠️ ${r}\n`; });
      md += `\n`;
    }

    md += `---\n\n`;
  });

  md += `*ClayPull — open-source contribution coach & AI IDE Studio*\n`;
  return md;
}

export function generateComparisonReport(comparison: ModelComparisonResult): string {
  const { modelA, modelB } = comparison;

  let md = `# ClayPull Model Comparison Report\n\n`;
  md += `| Metric | Model A (${modelA.config.model}) | Model B (${modelB.config.model}) |\n`;
  md += `| --- | --- | --- |\n`;
  md += `| **Provider** | ${modelA.config.provider} | ${modelB.config.provider} |\n`;
  md += `| **Latency** | ${(modelA.latencyMs / 1000).toFixed(2)}s | ${(modelB.latencyMs / 1000).toFixed(2)}s |\n`;
  md += `| **Issues Found** | ${modelA.result.issues.length} | ${modelB.result.issues.length} |\n`;
  md += `| **Avg Fit Score** | ${Math.round((modelA.result.issues.reduce((acc, i) => acc + i.fitScore, 0) / (modelA.result.issues.length || 1)) * 100)}% | ${Math.round((modelB.result.issues.reduce((acc, i) => acc + i.fitScore, 0) / (modelB.result.issues.length || 1)) * 100)}% |\n\n`;

  md += `## Model A Detailed Breakdown\n\n`;
  md += generateMarkdownReport(modelA.result);
  md += `\n---\n\n## Model B Detailed Breakdown\n\n`;
  md += generateMarkdownReport(modelB.result);

  return md;
}

export function downloadMarkdown(content: string, filename = 'firstpr-report.md') {
  const blob = new Blob([content], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}
